import { getJson } from './api';
import type {
  AuditCard,
  BookingCard,
  ConsentView,
  ContextualMessageView,
  DemandPeakView,
  EventCard,
  HeatmapView,
  InsightView,
  LiveData,
  MobilityCard,
  MetricCard,
  OrgCard,
  RoadmapView,
  RouteAdaptationView,
  TrafficView,
  UserCard,
} from './types';

export async function fetchCatalog(): Promise<LiveData> {
  const [
    events,
    mobility,
    bookings,
    operations,
    organizations,
    users,
    audit,
    roadmap,
    heatmaps,
    demandPeaks,
    routeAdaptations,
    contextualMessages,
    traffic,
    consents,
    insights,
  ] = await Promise.all([
    getJson<EventCard[]>('/api/v1/events'),
    getJson<MobilityCard[]>('/api/v1/mobility/options'),
    getJson<BookingCard[]>('/api/v1/bookings'),
    getJson<MetricCard[]>('/api/v1/operations/summary'),
    getJson<OrgCard[]>('/api/v1/admin/organizations'),
    getJson<UserCard[]>('/api/v1/identity/users'),
    getJson<AuditCard[]>('/api/v1/audit/entries'),
    getJson<RoadmapView[]>('/api/v1/platform/roadmap'),
    getJson<HeatmapView[]>('/api/v1/crowd/heatmaps'),
    getJson<DemandPeakView[]>('/api/v1/crowd/peaks'),
    getJson<RouteAdaptationView[]>('/api/v1/mobility/routes'),
    getJson<ContextualMessageView[]>('/api/v1/notifications/contextual'),
    getJson<TrafficView[]>('/api/v1/traffic/conditions'),
    getJson<ConsentView[]>('/api/v1/gps/consents'),
    getJson<InsightView[]>('/api/v1/intelligence/insights'),
  ]);

  return {
    events,
    mobility,
    bookings,
    operations,
    organizations,
    users,
    audit,
    roadmap,
    heatmaps,
    demandPeaks,
    routeAdaptations,
    contextualMessages,
    traffic,
    consents,
    insights,
  };
}
